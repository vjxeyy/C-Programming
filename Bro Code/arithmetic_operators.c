#include<stdio.h>

// arithmetic operators = + - * / % ++ --


int main() {


    int a = 10, b = 3;

    printf("%d\n", a + b);  // 13

    printf("%d\n", a - b);  // 7

    printf("%d\n", a * b);  // 30

    printf("%d\n", a / b);  // 3

    printf("%d\n", a % b);  // 1


    // increment operator

    int x = 5;
    x++;
    printf("%d\n", x);


    // decrement operator

    int y = 5;
    y--;
    printf("%d\n", y);
    


    return 0;
}
